"""LaTeX for the Phase 2b main tables (docs/phase2b_design.md §10-§11), same style as analysis/phase2_latex.py:
CI half-widths via \\ci{} (hide with \\renewcommand{\\showci}{0}), shaded own row, adjustbox. Cells come from
data/tables/phase2b/*.csv (phase2b_tables.py); blank = not run, \\na = not applicable.
Output: data/tables/phase2b/latex/{main_tables.tex, preview.tex}.
"""

import math
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
T = ROOT / "data/tables/phase2b"
OUT = T / "latex"
HEAD = r"""% Generated by analysis/phase2b_latex.py. Blank: not run yet. \na: not applicable.
\providecommand{\showci}{1}
\providecommand{\ci}[1]{\ifnum\showci=1 \,{\tiny$\pm$#1}\fi}
\providecommand{\na}{--}
\providecolor{oursbg}{gray}{0.92}
"""
OURS = {"ccg"}
GROUPS_ADV = [("", ["nodef"]), ("Prevention", ["repeat", "spotlight", "pidetector", "toolfilter", "promptarmor", "ipiguard", "melon_exec"]),
              ("Counterfactual", ["melon_all", "agentsentry", "causalarmor"]),
              ("Commit gate", ["ccg", "ccg_1shot", "ccg_block", "ccg_purify", "ccg_m", "ccg_ro", "ccg_mnzro", "ccg_nremove"])]
NAMES = {"nodef": "No defense", "repeat": "Repeat prompt", "spotlight": "Spotlighting", "pidetector": "DeBERTa detector", "toolfilter": "Tool filter",
         "promptarmor": "PromptArmor", "ipiguard": "IPIGuard-style", "melon_exec": "MELON (executor)", "melon_all": "MELON (every agent)",
         "agentsentry": "AgentSentry-style (executor)", "causalarmor": "CausalArmor-style (executor)", "ccg": r"\textbf{CCG (ours)}",
         "ccg_1shot": "\\quad 1 sample, no SPRT", "ccg_block": "\\quad block, no repair", "ccg_purify": "\\quad executor purification",
         "ccg_m": "\\quad masked only (M)", "ccg_ro": "\\quad re-observed only (Ro)", "ccg_mnzro": r"\quad M $\vee$ Nz $\vee$ Ro",
         "ccg_nremove": "\\quad N-remove neutralizer"}


def num(v) -> str:
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return ""
    s = f"{v:.2f}"
    return s[1:] if s.startswith("0.") else s


def cell(r, col: str, ci: bool = True, fmt=num) -> str:
    if r is None or col not in r or pd.isna(r[col]):
        return ""
    s = fmt(float(r[col]))
    lo, hi = r.get(f"{col}_lo"), r.get(f"{col}_hi")
    if ci and lo is not None and hi is not None and not pd.isna(lo) and not pd.isna(hi) and hi > lo:
        s += rf"\ci{{{num((hi - lo) / 2)}}}"
    return s


def cost(v: float) -> str:
    return f"{v:.1f}$\\times$"


def lookup(df: pd.DataFrame, **kv):
    if df is None or df.empty:
        return None
    m = df
    for k, v in kv.items():
        m = m[m[k] == v]
    return m.iloc[0].to_dict() if len(m) else None


def row(cells: list[str], ours: bool = False) -> str:
    if ours:
        cells = [cells[0], *(r"\cellcolor{oursbg}" + c for c in cells[1:])]
    return " & ".join(cells) + r" \\"


def wrap(caption: str, label: str, colspec: str, body: list[str], star: bool = True) -> str:
    env = "table*" if star else "table"
    return "\n".join([rf"\begin{{{env}}}[t]", r"\centering", rf"\caption{{{caption}}}", rf"\label{{{label}}}", r"\scriptsize",
                      r"\setlength{\tabcolsep}{2.5pt}", r"\begin{adjustbox}{max width=\linewidth}", rf"\begin{{tabular}}{{{colspec}}}",
                      r"\toprule", *body, r"\bottomrule", r"\end{tabular}", r"\end{adjustbox}", rf"\end{{{env}}}", ""])


def read(name: str) -> pd.DataFrame | None:
    p = T / name
    return pd.read_csv(p) if p.exists() else None


def table_adv() -> str:
    df, de = read("adv_main.csv"), read("adv_detect_entry.csv")
    body = [r"Group & Method & BU$\uparrow$ & UA$\uparrow$ & ASR$\downarrow$ & Det.\ upstream$\uparrow$ & Det.\ executor$\uparrow$ & Clean flag$\downarrow$ & Cost$\downarrow$ & Ovf. \\",
            r"\midrule"]
    for gi, (g, ms) in enumerate(GROUPS_ADV):
        for k, m in enumerate(ms):
            r = lookup(df, method=m)
            up, ex = lookup(de, method=m, entry="researcher"), lookup(de, method=m, entry="executor")
            prevent_like = m in ("repeat", "spotlight", "toolfilter", "ipiguard", "nodef")
            cells = [g if k == 0 else "", NAMES[m], cell(r, "BU"), cell(r, "UA"), cell(r, "ASR"),
                     r"\na" if prevent_like else cell(up, "detect"), r"\na" if prevent_like else cell(ex, "detect"),
                     r"\na" if prevent_like else cell(r, "clean_flag"), cell(r, "cost_benign", ci=False, fmt=cost),
                     "" if r is None or pd.isna(r.get("n_overflow_runs")) else str(int(r["n_overflow_runs"]))]
            body.append(row(cells, m in OURS))
        if gi < len(GROUPS_ADV) - 1:
            body.append(r"\midrule")
    cap = (r"AgentDojo v1.2.2, all 97 user tasks (949 attack cases, important\_instructions; 97 benign), three-agent pipeline, "
           r"Qwen3-8B. Detection: share of NoDef-successful attacks flagged, by the agent that first read the payload "
           r"(upstream = researcher). Cost: tokens $\times$ NoDef on benign runs. 95\% cluster-bootstrap CIs over user tasks.")
    cap += (r" Ovf.: runs where a call (or a gate replay) exceeded the 16k context and was scored as a stall; ASR and UA with "
            r"those runs or their user tasks excluded are in \texttt{adv\_overflow\_sensitivity.csv}.")
    return wrap(cap, "tab:ccg-adv", "llrrrrrrrr", body)


def table_acc() -> str:
    df, dp = read("acc_main.csv"), read("acc_by_point.csv")
    pts = ["R.tool", "R.out", "P.out", "S.write", "E.tool"]
    body = [r"Method & \multicolumn{3}{c}{Accidental} & \multicolumn{5}{c}{Adversarial detection by entry point} & Clean flag$\downarrow$ \\",
            r"\cmidrule(lr){2-4}\cmidrule(lr){5-9}",
            r" & Util$\uparrow$ & Harm$\downarrow$ & Cost$\downarrow$ & " + " & ".join(pts) + r" & \\", r"\midrule"]
    for m in ["nodef", "melon_exec", "melon_all", "agentsentry", "causalarmor", "ccg", "ccg_1shot", "ccg_block", "ccg_purify", "ccg_m", "ccg_ro"]:
        a, c = lookup(df, method=m, family="accidental"), lookup(df, method=m, family="clean")
        det = [r"\na" if m == "nodef" else cell(lookup(dp, method=m, family="adversarial", point=p), "detect") for p in pts]
        cells = [NAMES[m], cell(a, "utility"), cell(a, "harm"), cell(a, "cost", ci=False, fmt=cost), *det,
                 r"\na" if m == "nodef" else cell(c, "flag")]
        body.append(row(cells, m in OURS))
    cap = (r"Controlled faults on the 14-task pipeline set (both modes). Accidental: utility, residual harm (a committed write "
           r"carrying the corrupted value), cost $\times$ NoDef. Adversarial: detection by injection point.")
    return wrap(cap, "tab:ccg-acc", "lrrrrrrrrr", body)


def table_criteria() -> str:
    df = read("criteria.csv")
    body = [r"Id & Criterion & Estimate [95\% CI] & Result \\", r"\midrule"]
    for _, r in (df.iterrows() if df is not None else []):
        ci = f" [{num(r['lo'])}, {num(r['hi'])}]" if not pd.isna(r.get("lo")) and not pd.isna(r.get("hi")) else ""
        body.append(row([r["id"], str(r["criterion"]).replace("_", r"\_").replace("%", r"\%"), num(r["estimate"]) + ci,
                         "pass" if r["pass"] in (True, "True") else "fail"]))
    return wrap("Pre-registered success criteria (Amendment 9).", "tab:ccg-criteria", "llll", body, star=False)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    tex = HEAD + f"{table_adv()}\n{table_acc()}\n{table_criteria()}"
    (OUT / "main_tables.tex").write_text(tex)
    pre = (r"\documentclass{article}\usepackage{booktabs,multirow,graphicx,adjustbox}\usepackage[table]{xcolor}"
           r"\usepackage[margin=1.5cm,landscape]{geometry}\begin{document}" + "\n" + r"\input{main_tables.tex}" + "\n" + r"\end{document}")
    (OUT / "preview.tex").write_text(pre)
    print(OUT / "main_tables.tex")


if __name__ == "__main__":
    main()
