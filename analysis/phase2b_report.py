"""Markdown summary of the Phase 2b tables (data/tables/phase2b/*.csv -> data/tables/phase2b/summary.md) and compact per-run
exports (data/phase2b/*.csv.gz). Run after phase2b_tables.py."""

import json
import os
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
T = ROOT / "data/tables/phase2b"
X = ROOT / "data/phase2b"
RUNS = Path(os.path.expanduser(os.environ.get("FPR_RUNS", "~/fpr-runs")))


def ci(r, c: str) -> str:
    if c not in r or pd.isna(r[c]):
        return ""
    lo, hi = r.get(f"{c}_lo"), r.get(f"{c}_hi")
    s = f"{r[c]:.3f}"
    return s + (f" [{lo:.2f}, {hi:.2f}]" if lo is not None and not pd.isna(lo) and hi > lo else "")


def md(df: pd.DataFrame, cols: list[tuple[str, str]], keep: list[str] | None = None) -> str:
    head = "| " + " | ".join(h for h, _ in cols) + " |\n|" + "---|" * len(cols) + "\n"
    rows = []
    for _, r in df.iterrows():
        if keep is not None and r.get("method") not in keep:
            continue
        rows.append("| " + " | ".join(str(r[c]) if c in ("label", "family", "point", "entry", "set", "comparison", "metric", "n", "n_benign",
                                                              "n_attack", "n_overflow_runs") else (f"{r[c]:.2f}" if c.startswith("cost") and c in r
                                                                                                    and not pd.isna(r[c]) else ci(r, c))
                                    for _, c in cols) + " |")
    return head + "\n".join(rows) + "\n"


def summary() -> None:
    out = ["# Phase 2b results (generated by analysis/phase2b_report.py)\n",
           "95% cluster-bootstrap CIs over user tasks in brackets. Definitions: docs/phase2b_design.md.\n"]
    adv = pd.read_csv(T / "adv_main.csv")
    out += ["## AgentDojo v1.2.2, 97 user tasks (949 attack cases, 97 benign)\n",
            md(adv, [("Method", "label"), ("BU", "BU"), ("UA", "UA"), ("ASR", "ASR"), ("Clean flag", "clean_flag"),
                     ("Detect (NoDef-successful)", "detect_success"), ("Cost x NoDef (benign)", "cost_benign"), ("Overflow runs", "n_overflow_runs")])]
    de = pd.read_csv(T / "adv_detect_entry.csv")
    out += ["## Detection by entry point (AgentDojo; first agent that read the payload)\n",
            md(de, [("Method", "label"), ("Entry", "entry"), ("n", "n"), ("Detect", "detect"), ("ASR after", "ASR_after")])]
    acc = pd.read_csv(T / "acc_main.csv")
    out += ["## 14-task pipeline set (main_h2, seeds 100-101)\n",
            md(acc, [("Method", "label"), ("Family", "family"), ("n", "n"), ("Utility", "utility"), ("Harm", "harm"), ("Flag", "flag"), ("Cost", "cost")])]
    bp = pd.read_csv(T / "acc_by_point.csv")
    bp = bp[bp["family"] == "adversarial"]
    out += ["## Detection by injection point (14-task set, adversarial)\n",
            md(bp, [("Method", "label"), ("Point", "point"), ("n", "n"), ("Detect", "detect"), ("Harm", "harm")])]
    cr = pd.read_csv(T / "criteria.csv")
    out += ["## Pre-registered criteria (Amendment 9)\n", "| Id | Criterion | Estimate | Pass | Note |\n|---|---|---|---|---|\n"]
    out += [f"| {r['id']} | {r['criterion']} | {r['estimate']:.3f} | {r['pass']} | {r['note'] if isinstance(r['note'], str) else ''} |\n"
            for _, r in cr.iterrows()]
    ad = pd.read_csv(T / "adaptive.csv")
    out += ["\n## Adaptive attacks (A1 task-coupled; A2 delegated, benign)\n",
            md(ad, [("Set", "set"), ("Method", "label"), ("n", "n"), ("Utility", "utility"), ("Harm", "harm"), ("Flag", "flag"),
                    ("Flag M", "flag_M"), ("Flag Nz", "flag_Nz"), ("Flag Ro", "flag_Ro")])]
    ov = pd.read_csv(T / "adv_overflow_sensitivity.csv")
    out += ["## Context-overflow sensitivity (AgentDojo)\n",
            md(ov, [("Method", "label"), ("Overflow runs", "n_overflow_runs"), ("ASR all", "ASR_all"), ("ASR excl. runs", "ASR_excl_runs"),
                    ("ASR excl. tasks", "ASR_excl_tasks"), ("UA all", "UA_all"), ("UA excl. runs", "UA_excl_runs"), ("UA excl. tasks", "UA_excl_tasks")])]
    out += ["## Exploratory (not pre-registered)\n", "Detection of NoDef-successful upstream attacks minus clean flag rate (AgentDojo):\n\n"]
    yj = pd.read_csv(T / "exploratory_adv_youden.csv")
    out += ["| Method | Detect upstream | Clean flag | J |\n|---|---|---|---|\n"]
    out += [f"| {r['label']} | {r['detect_up']:.3f} | {r['clean_flag']:.3f} | {r['J']:.3f} |\n" for _, r in yj.iterrows()]
    pp = pd.read_csv(T / "exploratory_acc_paired.csv")
    out += ["\nPaired differences on the 14-task set (same runs F):\n\n",
            "| Comparison | Family | Metric | Estimate [95% CI] | n |\n|---|---|---|---|---|\n"]
    out += [f"| {r['comparison']} | {r['family']} | {r['metric']} | {r['estimate']:.3f} [{r['lo']:.2f}, {r['hi']:.2f}] | {r['n']} |\n"
            for _, r in pp.iterrows()]
    mv = pd.read_csv(T / "melon_validation.csv")
    out += ["\n## MELON validation (single-agent AgentDojo, banking + slack)\n",
            "| Row | BU | UA | ASR | Detect | Benign flag | Agreement vs official | dASR |\n|---|---|---|---|---|---|---|---|\n"]
    out += [f"| {r['cond']} | {r['BU']:.3f} | {r['UA']:.3f} | {r['ASR']:.3f} | {r['detect_attack']:.3f} | {r['flag_benign']:.3f} | "
            f"{'' if pd.isna(r.get('agreement_vs_official')) else f'{r.agreement_vs_official:.3f}'} | "
            f"{'' if pd.isna(r.get('delta_ASR_vs_official')) else f'{r.delta_ASR_vs_official:+.3f}'} |\n" for _, r in mv.iterrows()]
    (T / "summary.md").write_text("".join(out))


SUPERSEDED = {"base_causalarmor_adv_nodef"}  # pre-crash runs at gpu util 0.90; rerun as *_u80 (Amendment 12)
KEEP = ["task", "suite", "mode", "fault", "point", "entry", "injected", "branch_seed", "method", "utility", "security_violation", "residual_harm",
        "tainted_committed_writes", "flagged", "flagged_by_round0", "n_blocked", "repaired", "n_rounds", "n_samples", "n_overflow",
        "gate_new_calls", "gate_new_tokens", "detection", "flag_agent", "defense_tokens", "stalled", "checker_error"]


def export() -> None:
    """One compact CSV per experiment (summary fields only; traces stay in ~/fpr-runs)."""
    X.mkdir(parents=True, exist_ok=True)
    for exp in sorted(p.name for p in RUNS.iterdir() if p.name.startswith(("gate_", "base_")) or p.name in ("adv_nodef", "advtc_nodef", "a2_nodef")):
        if exp in SUPERSEDED:
            continue
        rows = []
        for p in sorted((RUNS / exp).glob("*/*/*/summary.json")):
            if (p.parent / "DONE").exists() and "." not in p.parent.name:
                s = json.loads(p.read_text())
                rows.append({k: (str(s[k]) if isinstance(s.get(k), (dict, list)) else s.get(k)) for k in KEEP if k in s})
        if rows:
            pd.DataFrame(rows).to_csv(X / f"{exp}.csv.gz", index=False, compression={"method": "gzip", "mtime": 0})


if __name__ == "__main__":
    summary()
    export()
    print(T / "summary.md", len(list(X.glob("*.csv.gz"))))
